function [Int_Cell, Int] = ImportInt

% Select folder
folderPath = uigetdir(pwd, 'Select folder containing TrackMate track files');

if isequal(folderPath,0)
    error('No folder selected.');
end

% Find csv files
fileList = dir(fullfile(folderPath, '*.csv'));
% sort csv files alphanumeric sort by filename
fileList = natsortfiles(fileList); 

% Import csvs
Int_Cell = cell(1, numel(fileList));
dataLines = [5, Inf];

for k = 1:numel(fileList)
    filePath = fullfile(folderPath, fileList(k).name);
    Int_Cell{k} = importMeanInt(filePath, dataLines);

end

Int = vertcat(Int_Cell{:});
end




